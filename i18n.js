let currentLang = localStorage.getItem('gcz_lang') || 'en';

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('gcz_lang', lang);
    
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.innerHTML = translations[lang][key]; // Pouzijeme innerHTML, aby fungovaly tagy jako <br>
        }
    });

    if (typeof window.updateDynamicDates === 'function') {
        window.updateDynamicDates();
    }
    
    if (typeof window.startTypewriter === 'function') {
        window.startTypewriter();
    }

    // Handle marquee special case
    const marquee = document.querySelector('.marquee-content');
    if (marquee) {
        const t = translations[lang]["marquee.text"];
        marquee.innerText = t + " • " + t + " • " + t + " • " + t + " • ";
    }

    // Update toggles
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active-lang');
        } else {
            btn.classList.remove('active-lang');
        }
    });
}

document.addEventListener('DOMContentLoaded', () => {
    // Setup toggle listeners
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            setLanguage(btn.getAttribute('data-lang'));
        });
    });

    // Apply initial language
    setLanguage(currentLang);
});
